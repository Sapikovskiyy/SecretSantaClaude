/** Screens for review: room customization and profile editor (390 px). */
import { test } from '@playwright/test'
import { mkdirSync } from 'node:fs'

test('personalize screens', async ({ page }) => {
  mkdirSync('screenshots/personalize', { recursive: true })
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.goto('/')
  await page.getByRole('button', { name: 'Начать' }).click()
  await page.waitForURL(/\/home$/)
  await page.goto('/rooms/r-newyear/customize')
  await page.waitForTimeout(900)
  await page.getByRole('radio', { name: 'Сани' }).click()
  await page.getByRole('radio', { name: 'Красная', exact: true }).click()
  await page.waitForTimeout(800)
  await page.screenshot({ path: 'screenshots/personalize/1-customize.png', fullPage: true })
  await page.getByRole('button', { name: 'Сохранить' }).click()
  await page.waitForTimeout(900)
  await page.goto('/home')
  await page.waitForTimeout(900)
  await page.screenshot({ path: 'screenshots/personalize/2-home.png' })
  await page.goto('/profile/edit')
  await page.waitForTimeout(800)
  await page.getByLabel('Имя', { exact: true }).fill('Даниил')
  await page.getByRole('radio', { name: 'Талисман santa' }).click()
  await page.getByLabel('О себе', { exact: true }).fill('Люблю горы, кофе и настолки')
  await page.getByRole('radiogroup', { name: 'Размер одежды' }).getByRole('radio', { name: 'M', exact: true }).click()
  await page.waitForTimeout(700)
  await page.screenshot({ path: 'screenshots/personalize/3-profile-edit.png', fullPage: true })
  await page.getByRole('button', { name: 'Сохранить' }).click()
  await page.waitForTimeout(1200)
  await page.screenshot({ path: 'screenshots/personalize/4-profile.png' })
})
